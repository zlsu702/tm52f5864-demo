//功能：IO初始化，IO默认输出都为1
//输入参数：无
//输出参数：无
//备注：
//=============================================================================
void IO_Init(void)
{
	P0 = 0x00;
	// 00000000B
	// |||||||\---- LE1		  
	// ||||||\----- SCLK1
	// |||||\------ 				
	// ||||\------- SDA1
	// |||\-------- SDA2
	// ||\--------- 
	// |\---------- PWM1-OE
	// \----------- SCK2
	P0MOD10 = (P0MOD10&~0x0f)|2<<0;	  
	P0MOD10 = (P0MOD10&~0xf0)|2<<4;	
	P0MOD32 = (P0MOD32&~0x0f)|2<<0;		
	P0MOD32 = (P0MOD32&~0xf0)|2<<4;	
	P0MOD54 = (P0MOD54&~0x0f)|2<<0;	
	P0MOD54 = (P0MOD54&~0xf0)|2<<4;
	P0MOD76 = (P0MOD76&~0x0f)|2<<0;	
	P0MOD76 = (P0MOD76&~0xf0)|2<<4;

	
	P1 = 0x47;
	// 01000111B
	// |||||||\---- ADC_VR 		  
	// ||||||\----- CON
	// |||||\------ RF_DAT 						
	// ||||\------- 
	// |||\-------- 
	// ||\--------- 
	// |\---------- SDA
	// \----------- 
	P1MOD10 = (P1MOD10&~0x0f)|3<<0;	  
	P1MOD10 = (P1MOD10&~0xf0)|2<<4;	
	P1MOD32 = (P1MOD32&~0x0f)|1<<0;	
	P1MOD32 = (P1MOD32&~0xf0)|2<<4;
	P1MOD54 = (P1MOD54&~0x0f)|2<<0;	
	P1MOD54 = (P1MOD54&~0xf0)|2<<4;
	P1MOD76 = (P1MOD76&~0x0f)|1<<0;	
	P1MOD76 = (P1MOD76&~0xf0)|2<<4;
	
	P2 = 0x0E;
	// 00001110B
	// |||||||\---- PWM-BZ    
	// ||||||\----- DC_DET
	// |||||\------	OSCX
	// ||||\-------	OSCX 
	// |||\--------  
	// ||\---------   
	// |\---------- 
	// \----------- 
	P2MOD10 = (P2MOD10&~0x0f)|2<<0;	  
	P2MOD10 = (P2MOD10&~0xf0)|1<<4;	
	P2MOD32 = (P2MOD32&~0x0f)|0<<0;	
	P2MOD32 = (P2MOD32&~0xf0)|0<<4;
	P2MOD54 = (P2MOD54&~0x0f)|2<<0;	
	P2MOD54 = (P2MOD54&~0xf0)|2<<4;

	P3 = 0x4C;
	// 01001100B
	// |||||||\---- 		   
	// ||||||\----- 
	// |||||\------ ADC_KEY
	// ||||\------- P_LED
	// |||\-------- LE2
	// ||\--------- SEG1
	// |\---------- SCK
	// \----------- SEG2	
	P3MOD10 = (P3MOD10&~0x0f)|2<<0;	  
	P3MOD10 = (P3MOD10&~0xf0)|2<<4;	
	P3MOD32 = (P3MOD32&~0x0f)|3<<0;	
	P3MOD32 = (P3MOD32&~0xf0)|2<<4;	
	P3MOD54 = (P3MOD54&~0x0f)|2<<0;	
	P3MOD54 = (P3MOD54&~0xf0)|2<<4;
	P3MOD76 = (P3MOD76&~0x0f)|2<<0;	
	P3MOD76 = (P3MOD76&~0xf0)|2<<4;				
	
	INTE1 = 0;
	EX1 = 0;
	EX0 = 0;
	INTFLG = 0;		//io 中断标志
	IE1 = 0;
	IE0 = 0;
}

