void ADC_Init(void)
{
	//ADC Clock Rate:SysClk/8
	OPTION = (OPTION & ADCKS_Mask)|ADCKS_sys_16;
	ADCVERFS_VCC;		//VCC
//	ADCHSEL = ADCVERFS|VBG_01;		//VBG 2.0v
	//清ADC中断标志位	
	INTFLG = ~ADIF;						
}

u16 ADC_Convert( uchar Adc_ch )
{
  	static u16 adcNum;
  	uchar adcNumH;
  	uchar adcNumL;
  	ADCHSEL	= (ADCHSEL & ~0xf8)|Adc_ch;
  	ADSOC = 1;
  	while(ADSOC==1);
  	
  	adcNumL = ADCDL&0xF0;
  	adcNumH = ADCDH;
  	
  	adcNum = adcNumH*256 + adcNumL;
  	adcNum = (adcNum>>4)&0x0fff;
  	return(adcNum);
} 

u8 ADC_Convert1( uchar Adc_ch )
{
  	uchar adcNum;
  	ADCHSEL	= (ADCHSEL & ~0xf8)|Adc_ch;
  	ADSOC = 1;
  	while(ADSOC==1);
  	
  	adcNum = ADCDH;
  	
  	return(adcNum);
} 

