//=============================================================================
//功能：定时器0初始化，定时模式，优先级为1
//输入参数：无
//输出参数：无
//备注：
//=============================================================================
void TM0_Init(void)
{		
	ET0= 0;			//TM0中断禁止	
	TR0= 0;			//TM0停止

	//屏蔽TM0门控信号
	TMOD &= ~GATE0;
	//计时模式（重要）	
	TMOD &= ~CT0;
	//TM0以方式1工作,16位计时/计数器
	TMOD = (TMOD & T0_Mask) | T0_Mode1;
	
	//定时时间
	TH0 = D_TM0H;								
	TL0 = D_TM0L;															
	
	//TM0 中断优先级为0
	IP &= ~PT0;									
	IPH &= ~IPH_PT0H;													
																
	ET0 = 1;								//TM0中断使能
	TF0 = 0;								//TM0中断标志清零
	TR0 = 1;								//TM0开启
}
//=============================================================================
//功能：定时器0开启
//输入参数：无
//输出参数：无
//备注：
//=============================================================================
void TM0_Enable(void)
{
	ET0 = 0;								//TM0中断使能
	TR0 = 0;	
	//定时时间
	TH0=D_TM0H;								
	TL0=D_TM0L;								//TM0开启
	ET0 = 1;								//TM0中断使能
	TF0 = 0;								//TM0中断标志清零
	TR0 = 1;	
}
