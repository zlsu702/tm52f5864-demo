void PWM_Init(void)
{
	CLRPWM0 = 1; 				//PWM0关闭
	CLRPWM1 = 1; 				//PWM0关闭
	PWMCON = 0x00;				//PWM FSYSCLK
	PWMCON2 = 0x00;				//正常模式
	PWM0PRDL = 0xca;			//PWM0周期
	PWM0PRDH = 0x08;			//PWM0周期
	PWM1PRD = 0xff;				//PWM1周期 2k
	AUX3 = (AUX3&~0xe0)|0xA0;		//PWM1~6频率分频/32
	
	PWM0DL = 0x00;			 	//PWM0占空比
	PWM0DH = 0x00;
	PWM1D = 0;			 	//PWM1占空比
	PWM2D = 0;
	PWM3D = 0;
	PWM4D = 0;
	PWM5D = 0;
	PWM6D = 0;
}

void PWM_ALL_Off(void)
{
	CLRPWM1 = 1;	
	PWMCON &= ~PWM1EN;
	P0MOD76 = (P0MOD76&~0x0f)|2<<0;
	P0_6 = 0;
	P2MOD10 = (P2MOD10&~0x0f)|2<<0;
	P2_0 = 0;
}


void PWM_On(void)
{
	uchar tmp_duty;
	tmp_duty =9*DispLevel/10;
	if(DispLevel)
	{
		PWM1D = 255-tmp_duty;	
		P0MOD76 = (P0MOD76&~0x0f)|11<<0;
	}	
	else
	{
		P0MOD76 = (P0MOD76&~0x0f)|2<<0;
		P0_6 = 1;
	}	
	CLRPWM1 = 0;	
	PWMCON |= PWM1EN;
}		

void PWM_Off(void)
{
	P0MOD76 = (P0MOD76&~0x0f)|2<<0;
	P0_6 = 0;
}	

