void TM3_Init(void)
{
	CLRTM3 = 1;							//清除TM3
	OPTION &= ~TM3CKS;
	TM3RLD = (((unsigned long)0x10000-16384)>>8)&0xFF;		//溢出周期=500ms
	INTFLG &= ~TF3;							//清TM3中断标志
	IP1 &= ~PT3;
	IP1H &= ~PT3H;							//TM3中断优先级0
	INTE1 |= TM3IE;							//TM3中断使能
	CLRTM3 = 0;							//开启TM3
}

