//输出参数：无
//备注：	上电默认 Fsys = SRC，切换为 Fsys = FRC = 16.5888MHz/2 = 8.2944MHz
//=============================================================================
void InitDevice(void)
{
	EA=0;						//关闭总中断开关
	OPTION = WDTPSC_02;				//看门狗定时132ms
	AUX2  = 0;
	AUX1  = 0;
	WDT_RUN_FAST_DIS_ILDE;				//看门狗开
	PDOWN_LVD_DISABLE;
	LVRCON = LVRSEL_0011;			//LVR = 2.3V
	SysClk_Init();
	IO_Init();	
	ADC_Init();
	TM0_Init();
	TM1_Init();
	TM3_Init();
	PWM_Init();
	EA=1;						//开启总中断开关
}
